$(function () {


    /* ==========================================================
       HEADER 2DEPTH MENU
    ========================================================== */

    const $header = $(".header");

    const $mainMenu = $(".gnb > li");

    const $depth2 = $(".depth2");



    /* ==========================================================
       주메뉴에 마우스를 올렸을 때
    ========================================================== */

    $mainMenu.on("mouseenter", function () {


        /* 모든 메뉴의 active 제거 */
        $mainMenu.removeClass("is-active");


        /* 현재 마우스를 올린 메뉴만 active */
        $(this).addClass("is-active");



        /* ======================================================
           2단 메뉴가 닫혀 있는 경우에만

           jQuery slideDown()을 이용하여
           위에서 아래 방향으로 메뉴를 펼침
        ====================================================== */

        if (!$depth2.is(":visible")) {

            $depth2
                .stop(true, true)
                .slideDown(250);

        }


    });



    /* ==========================================================
       HEADER + 2DEPTH 전체 영역에서
       마우스가 벗어났을 때
    ========================================================== */

    $header.on("mouseleave", function () {


        /* ========================================
           2단 메뉴 닫기
        ========================================= */

        $depth2
            .stop(true, true)
            .slideUp(220);



        /* ========================================
           active 메뉴 제거
        ========================================= */

        $mainMenu.removeClass("is-active");


    });



    /* ==========================================================
       href="#" 기본 동작 방지
    ========================================================== */

    $(".main-menu, .depth2-menu a")
        .on("click", function (e) {


            if ($(this).attr("href") === "#") {

                e.preventDefault();

            }


        });



    /* ==========================================================
       전체 슬라이드 개수 구하기

       현재
       slide01
       slide02
       slide03

       총 3개
    ========================================================== */

    const totalSlides =
        $(".mainSwiper .swiper-wrapper > .swiper-slide").length;



    /* ==========================================================
       MAIN SWIPER SLIDE
    ========================================================== */

    const mainSwiper = new Swiper(".mainSwiper", {


        /* ======================================================
           슬라이드 이동 방향

           horizontal = 좌우 방향
        ====================================================== */

        direction: "horizontal",



        /* ======================================================
           마지막 슬라이드 이후
           다시 첫 번째 슬라이드로 이동
        ====================================================== */

        loop: true,



        /* ======================================================
           슬라이드 이동 애니메이션 속도

           800 = 0.8초
        ====================================================== */

        speed: 800,



        /* ======================================================
           자동 슬라이드

           3000 = 3초마다 자동 실행
        ====================================================== */

        autoplay: {


            /* 3초 */
            delay: 3000,


            /* ==================================================
               좌우 버튼을 직접 눌러도
               자동 슬라이드를 멈추지 않음
            ================================================== */

            disableOnInteraction: false


        },



        /* ======================================================
           좌우 NAVIGATION BUTTON
        ====================================================== */

        navigation: {


            /* 다음 버튼 */
            nextEl: ".slide-next",


            /* 이전 버튼 */
            prevEl: ".slide-prev"


        },



        /* ======================================================
           SWIPER EVENT
        ====================================================== */

        on: {


            /* ==================================================
               Swiper 처음 실행될 때
            ================================================== */

            init: function () {


                updateSlidePage(this);


            },



            /* ==================================================
               슬라이드가 변경될 때마다
               페이지 번호 변경
            ================================================== */

            slideChange: function () {


                updateSlidePage(this);


            }


        }


    });



    /* ==========================================================
       PAGE NUMBER FUNCTION

       1/3
       2/3
       3/3
    ========================================================== */

    function updateSlidePage(swiper) {


        /* ======================================================
           realIndex는

           첫 번째 = 0
           두 번째 = 1
           세 번째 = 2

           로 시작하므로 +1 처리
        ====================================================== */

        const current = swiper.realIndex + 1;



        /* ======================================================
           현재 슬라이드 번호 출력
        ====================================================== */

        $(".current-page").text(current);



        /* ======================================================
           전체 슬라이드 개수 출력
        ====================================================== */

        $(".total-page").text(totalSlides);


    }


});

$(function () {

    // =========================================
    // 탭 메뉴 클릭 기능
    // =========================================
    $(".tab li").click(function () {

        // 사용자가 클릭한 탭의 순번 구하기
        let num = $(this).index();

        // 모든 탭의 on 제거
        $(".tab li").removeClass("on");

        // 클릭한 탭에 on 추가
        $(this).addClass("on");

        // 모든 상품 리스트 숨기기
        $(".brand_list").removeClass("on");

        // 클릭한 탭 순번과 같은 상품 리스트 보여주기
        $(".brand_list").eq(num).addClass("on");

    });

});