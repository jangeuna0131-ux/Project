/* ========================================
   설화수 추천 Swiper
======================================== */

const recommendSwiper = new Swiper(".recommend-swiper", {

    /* ========================================
       한 화면에 보여주는 슬라이드 개수
    ======================================== */
    slidesPerView: 3,


    /* ========================================
       카드 사이 간격
    ======================================== */
    spaceBetween: 24,


    /* ========================================
       한 번 이동할 때 1개씩
    ======================================== */
    slidesPerGroup: 1,


    /* ========================================
       무한 반복

       1 2 3
       2 3 4
       3 4 5
       4 5 6
       5 6 1
       6 1 2
       1 2 3

       계속 한쪽 방향으로 이어짐
    ======================================== */
    loop: true,


    /* ========================================
       총 상품 6개를 loop용으로 복제
    ======================================== */
    loopedSlides: 6,


    /* ========================================
       슬라이드 이동 속도

       600ms = 너무 느리지 않게 휘리릭
    ======================================== */
    speed: 600,


    /* ========================================
       자동 슬라이드
    ======================================== */
    autoplay: {

        /* 3초마다 자동 이동 */
        delay: 3000,

        /* 다음 방향으로 이동 */
        reverseDirection: false,

        /* 버튼 클릭 후에도 자동재생 유지 */
        disableOnInteraction: false

    },


    /* ========================================
       이전 / 다음 버튼
    ======================================== */
    navigation: {

        /* 오른쪽 버튼 */
        nextEl: ".recommend-next",

        /* 왼쪽 버튼 */
        prevEl: ".recommend-prev"

    },


    /* ========================================
       진행 막대
    ======================================== */
    pagination: {

        el: ".recommend-swiper-pagination",

        type: "progressbar"

    }

});


/* ========================================
   정지 / 재생 버튼
======================================== */

const controlBtn =
    document.querySelector(".recommend-control-btn");


/* 현재 정지 여부 */
let isPaused = false;


/* ========================================
   정지 / 재생 버튼 클릭
======================================== */

controlBtn.addEventListener("click", function () {


    /* ========================================
       현재 재생 중 → 정지
    ======================================== */
    if (isPaused === false) {

        /* 자동재생 정지 */
        recommendSwiper.autoplay.stop();


        /* 재생 아이콘으로 변경 */
        controlBtn.classList.add("play");


        /* 접근성 문구 */
        controlBtn.setAttribute(
            "aria-label",
            "슬라이드 재생"
        );


        /* 정지 상태 */
        isPaused = true;

    }


    /* ========================================
       현재 정지 중 → 재생
    ======================================== */
    else {

        /* 자동재생 다시 시작 */
        recommendSwiper.autoplay.start();


        /* 정지 아이콘으로 변경 */
        controlBtn.classList.remove("play");


        /* 접근성 문구 */
        controlBtn.setAttribute(
            "aria-label",
            "슬라이드 정지"
        );


        /* 재생 상태 */
        isPaused = false;

    }

});